import { Injectable } from '@nestjs/common';
import { randomUUID } from 'crypto';
import {
  createReadStream,
  createWriteStream,
  promises as fs,
  ReadStream,
  WriteStream,
} from 'fs';
import { dirname, isAbsolute, relative, resolve, sep } from 'path';
import { ExportFormat } from './entities/export-job.entity';

const DEFAULT_ROOT = './storage/exports';
/** directory `main.ts` serves publicly under `/uploads/`; export files must never live below it */
const PUBLIC_UPLOADS = 'uploads';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const KEY = /^[0-9a-f-]{36}\/[0-9a-f-]{36}\.(csv|pdf)$/;

export class UnsafeStorageKeyError extends Error {
  constructor(key: string) {
    super(`unsafe export storage key ${JSON.stringify(key.slice(0, 80))}`);
    this.name = 'UnsafeStorageKeyError';
  }
}

/**
 * A file being written: bytes go to a private `<key>.<random>.part` (two workers never share one after a
 * lease takeover); `commit` renames it into place atomically, `abort` removes it.
 */
export interface PendingObject {
  stream: WriteStream;
  commit(): Promise<void>;
  abort(): Promise<void>;
}

function within(root: string, path: string): boolean {
  const rel = relative(root, path);
  return rel !== '' && !rel.startsWith('..') && !isAbsolute(rel);
}

/**
 * Export file store (plan 2.9): a private directory from `EXPORT_STORAGE_DIR` (default
 * `./storage/exports`, a volume shared by the API and the worker), never the publicly served `uploads`
 * directory. Keys are generated by the server from the tenant and job ids (`<tenant>/<job>.<csv|pdf>`); every key
 * is checked against that shape and resolved inside the root, so a stored or forged key can never reach
 * another path (no traversal).
 */
@Injectable()
export class ExportStorage {
  root(): string {
    const root = resolve(process.env.EXPORT_STORAGE_DIR || DEFAULT_ROOT);
    const uploads = resolve(PUBLIC_UPLOADS);
    if (root === uploads || within(uploads, root)) {
      throw new Error(
        'EXPORT_STORAGE_DIR must not be inside the publicly served uploads directory',
      );
    }
    return root;
  }

  keyOf(tenantId: string, jobId: string, format: ExportFormat = 'csv'): string {
    if (!UUID.test(tenantId) || !UUID.test(jobId)) {
      throw new UnsafeStorageKeyError(`${tenantId}/${jobId}`);
    }
    return `${tenantId}/${jobId}.${format}`;
  }

  /** Absolute path of a key inside the root; throws for anything else. */
  pathOf(key: string): string {
    const root = this.root();
    if (!KEY.test(key)) throw new UnsafeStorageKeyError(key);
    const path = resolve(root, ...key.split('/'));
    if (!within(root, path) || !path.startsWith(root + sep)) {
      throw new UnsafeStorageKeyError(key);
    }
    return path;
  }

  async openWrite(key: string): Promise<PendingObject> {
    const path = this.pathOf(key);
    const partial = `${path}.${randomUUID()}.part`;
    await fs.mkdir(dirname(path), { recursive: true });
    const stream = createWriteStream(partial, { flags: 'w', mode: 0o600 });
    const closed = () =>
      new Promise<void>((done, fail) => {
        if (stream.closed) return done();
        stream.once('error', fail);
        stream.end(() => done());
      });
    return {
      stream,
      commit: async () => {
        await closed();
        await fs.rename(partial, path);
      },
      abort: async () => {
        // destroy() returns before the handle is closed (or even opened); removing the file earlier
        // races the stream and can leave the partial behind (seen on Windows)
        await releaseStream(stream);
        await fs.rm(partial, { force: true });
      },
    };
  }

  openRead(key: string): ReadStream {
    return createReadStream(this.pathOf(key));
  }

  async exists(key: string): Promise<boolean> {
    try {
      return (await fs.stat(this.pathOf(key))).isFile();
    } catch (error: unknown) {
      if (error instanceof UnsafeStorageKeyError) throw error;
      return false;
    }
  }

  async remove(key: string): Promise<void> {
    await fs.rm(this.pathOf(key), { force: true });
  }
}

/** Destroys `stream` and resolves once its file handle is released. */
function releaseStream(stream: WriteStream): Promise<void> {
  if (stream.closed) return Promise.resolve();
  return new Promise((resolve) => {
    stream.once('close', () => resolve());
    stream.destroy();
  });
}
