/**
 * Reference extraction of one tenant: checks the plan against the source catalogue, then writes one
 * seed file per table group (tables in foreign-key order, rows in a deterministic order) and returns
 * the manifest. Runs inside the caller's read-only transaction.
 */
import { mkdirSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { ForeignKey, orderTables, selfReferenceColumn } from './fk-order';
import { SeedManifest } from './manifest';
import { countRows, readRows, unsatisfiedReferences } from './row-reader';
import {
  foreignKeys,
  primaryKey,
  Queryable,
  tableColumns,
  tableNames,
} from './source-catalog';
import { insertStatement, sqlFile } from './sql-writer';
import {
  assertTablesExist,
  groupPath,
  planTables,
  rowFilter,
  TABLE_GROUPS,
  TableGroup,
} from './table-plan';

export interface ExtractOptions {
  tenantCode: string;
  /** Seed directory (`db/seed`): files go to reference/ and generated/ below it. */
  out: string;
  /** Called with `<table> <rows>` after each table is written. */
  report: (line: string) => void;
}

interface Source {
  tenantId: string;
  organizationId: string;
  organizationCode: string;
}

interface GroupContext {
  options: ExtractOptions;
  source: Source;
  fks: ForeignKey[];
  counts: Record<string, number>;
}

async function resolveSource(
  db: Queryable,
  tenantCode: string,
): Promise<Source> {
  const tenant = await db.query<{ id: string; organization_id: string | null }>(
    'SELECT id, organization_id FROM tenants WHERE code = $1',
    [tenantCode],
  );
  if (tenant.rows.length !== 1)
    throw new Error(`tenant ${tenantCode} not found`);
  const { id, organization_id: organizationId } = tenant.rows[0];
  if (!organizationId)
    throw new Error(`tenant ${tenantCode} has no organisation`);
  const org = await db.query<{ code: string }>(
    'SELECT code FROM organizations WHERE id = $1',
    [organizationId],
  );
  if (org.rows.length !== 1)
    throw new Error(`organisation ${organizationId} not found`);
  return { tenantId: id, organizationId, organizationCode: org.rows[0].code };
}

/** Every plan foreign key must point to a table loaded by the same or an earlier file. */
function assertFileOrder(fks: ForeignKey[]): void {
  const fileOf = new Map<string, number>();
  TABLE_GROUPS.forEach((group, index) =>
    group.tables.forEach((table) => fileOf.set(table, index)),
  );
  for (const fk of fks) {
    const from = fileOf.get(fk.table);
    const to = fileOf.get(fk.references);
    if (from !== undefined && to !== undefined && to > from) {
      throw new Error(
        `${fk.table}.${fk.column} references ${fk.references}, which a later file loads`,
      );
    }
  }
}

async function tableStatements(
  db: Queryable,
  table: string,
  filter: string,
  fks: ForeignKey[],
): Promise<string[]> {
  const columns = await tableColumns(db, table);
  const names = columns.map((column) => column.name);
  const typeMap = Object.fromEntries(
    columns.map((column) => [column.name, column.type]),
  );
  const selfColumn = selfReferenceColumn(table, fks);
  const selfFk = fks.find(
    (fk) => fk.table === table && fk.column === selfColumn,
  );
  const rows = await readRows(db, {
    table,
    columns: names,
    primaryKey: await primaryKey(db, table),
    filter,
    selfReference: selfColumn
      ? { column: selfColumn, referenced: selfFk?.referencedColumn ?? 'id' }
      : null,
  });
  const inserts = rows.map((row) =>
    insertStatement(table, names, row, typeMap),
  );
  return [`-- ${table}: ${rows.length} rows`, ...inserts];
}

function writeText(path: string, text: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text, 'utf8');
}

async function writeGroup(
  db: Queryable,
  group: TableGroup,
  ctx: GroupContext,
): Promise<string[]> {
  const ordered = orderTables([...group.tables], ctx.fks);
  const statements: string[] = [];
  for (const table of ordered) {
    const filter = rowFilter(
      table,
      ctx.source.tenantId,
      ctx.source.organizationId,
    );
    statements.push(...(await tableStatements(db, table, filter, ctx.fks)));
    ctx.counts[table] = await countRows(db, table, filter);
    ctx.options.report(`${table} ${ctx.counts[table]}`);
  }
  const header =
    `-- ${group.file}: generated by npm run deploy:extract-reference (TF-PREP-001), ` +
    `tenant ${ctx.options.tenantCode}. Do not edit; re-extract.`;
  writeText(
    join(ctx.options.out, groupPath(group.file)),
    sqlFile(header, statements),
  );
  return ordered;
}

/** Refuses a seed that would break a foreign key (reference outside the plan or the tenant). */
async function checkReferences(
  db: Queryable,
  source: Source,
  fks: ForeignKey[],
): Promise<void> {
  const filters = new Map(
    planTables().map((t) => [
      t,
      rowFilter(t, source.tenantId, source.organizationId),
    ]),
  );
  const unsatisfied = await unsatisfiedReferences(db, fks, filters);
  if (unsatisfied.length > 0) {
    throw new Error(
      `references the seed cannot satisfy:\n  ${unsatisfied.join('\n  ')}`,
    );
  }
}

export async function extractReference(
  db: Queryable,
  options: ExtractOptions,
): Promise<SeedManifest> {
  assertTablesExist(await tableNames(db));
  const source = await resolveSource(db, options.tenantCode);
  const fks = await foreignKeys(db, planTables());
  assertFileOrder(fks);
  await checkReferences(db, source, fks);
  const ctx: GroupContext = { options, source, fks, counts: {} };
  const files: Record<string, string[]> = {};
  for (const group of TABLE_GROUPS) {
    files[group.file] = await writeGroup(db, group, ctx);
  }
  return {
    extractedAt: new Date().toISOString(),
    sourceDatabase: 'proact',
    tenantCode: options.tenantCode,
    organizationCode: source.organizationCode,
    tenantId: source.tenantId,
    organizationId: source.organizationId,
    tables: ctx.counts,
    files,
  };
}
